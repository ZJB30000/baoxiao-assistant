"""疑似违规巡检查问答的识别规则（阶段3）。

口径：员工问题里出现“规避检查/应付检查”意图的关键词时，该问答在审计页
标红。关键词是朴素启发式，够课程演示；生产环境应换成分类模型并保留申诉通道。
"""

VIOLATION_KEYWORDS = (
    "应付检查", "蒙混", "先补记录", "补签", "代签", "别写", "瞒报",
    "不被发现", "照片代替复查", "代替复查", "跳过检查", "怎么才能不被",
)


def scan(question: str) -> bool:
    """命中任一关键词即视为疑似违规。"""
    return any(k in question for k in VIOLATION_KEYWORDS)
